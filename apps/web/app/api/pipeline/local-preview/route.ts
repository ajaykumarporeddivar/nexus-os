import { spawn } from 'child_process'
import { createWriteStream } from 'fs'
import { mkdir, symlink, writeFile } from 'fs/promises'
import net from 'net'
import path from 'path'
import { NextRequest, NextResponse } from 'next/server'
import { requireSession } from '@/lib/session'

const MAX_FILES = 120
const MAX_FILE_CHARS = 300_000
const PREVIEW_PORT_START = 4300
const PREVIEW_PORT_END = 4310
const BLOCKED_SEGMENTS = new Set(['node_modules', '.next', '.git', '.vercel'])
const BLOCKED_FILENAMES = new Set(['.env', '.env.local', '.env.production', '.env.development'])

type LocalPreviewBody = {
  projectName?: string
  files?: Record<string, string>
}

function slugify(input: string): string {
  return input
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60) || 'nexus-preview'
}

function resolveWorkspaceRoots(): { repoRoot: string; appRoot: string } {
  const cwd = process.cwd()
  const isWebApp = cwd.endsWith(`${path.sep}apps${path.sep}web`)
  const repoRoot = isWebApp ? path.resolve(cwd, '..', '..') : cwd
  const appRoot = isWebApp ? cwd : path.resolve(cwd, 'apps', 'web')
  return { repoRoot, appRoot }
}

function safeRelativeFilePath(filePath: string): string | null {
  const normalizedInput = filePath.replace(/\\/g, '/').replace(/^\/+/, '')
  const segments = normalizedInput.split('/').filter(Boolean)
  if (segments.length === 0) return null
  if (segments.some(segment => segment === '..' || BLOCKED_SEGMENTS.has(segment))) return null
  if (BLOCKED_FILENAMES.has(segments[segments.length - 1])) return null

  const normalized = path.normalize(segments.join(path.sep))
  if (path.isAbsolute(normalized) || normalized.startsWith('..')) return null
  return normalized
}

