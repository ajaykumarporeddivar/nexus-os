async function isPortAvailable(port: number): Promise<boolean> {
  return new Promise(resolve => {
    const server = net.createServer()
    server.once('error', () => resolve(false))
    server.once('listening', () => {
      server.close(() => resolve(true))
    })
    server.listen(port, '127.0.0.1')
  })
}

async function waitForPreview(url: string, timeoutMs = 90_000): Promise<boolean> {
  const deadline = Date.now() + timeoutMs
  const urls = [url, `${url}/dashboard`]
  while (Date.now() < deadline) {
    for (const candidate of urls) {
      try {
        const res = await fetch(candidate, { cache: 'no-store' })
        if (res.ok) return true
      } catch {
        // Server is still compiling or not listening yet.
      }
    }
    await new Promise(resolve => setTimeout(resolve, 2000))
  }
  return false
}

async function startPreviewServer(previewDir: string, appRoot: string, port: number): Promise<{ url: string; logPath: string; ready: boolean; command: string }> {
  const url = `http://127.0.0.1:${port}`
  const nextBin = path.join(appRoot, 'node_modules', 'next', 'dist', 'bin', 'next')
  const logPath = path.join(previewDir, 'nexus-local-preview.log')

  // Ensure the log file exists before spawning so createWriteStream has a valid fd on Windows.
  // On Windows, passing a WriteStream whose fd is null to stdio throws ERR_INVALID_ARG_VALUE.
  // We open the stream and wait for the 'open' event before spawning the child process.
  const out = createWriteStream(logPath, { flags: 'a' })
  await new Promise<void>((resolve, reject) => {
    out.once('open', () => resolve())
    out.once('error', reject)
  })

  const child = spawn(process.execPath, [nextBin, 'dev', '-p', String(port), '-H', '127.0.0.1'], {
    cwd: previewDir,
    detached: true,
    env: {
      ...process.env,
      NEXT_TELEMETRY_DISABLED: '1',
      PORT: String(port),
    },
    stdio: ['ignore', out, out],
    windowsHide: true,
  })
  child.unref()

  return {
    url,
    logPath,
    ready: await waitForPreview(url),
    command: `node "${nextBin}" dev -p ${port} -H 127.0.0.1`,
  }
}

async function startPreviewServerWithPortRetry(previewDir: string, appRoot: string): Promise<{ url: string; logPath: string; ready: boolean; command: string; port: number }> {
  let lastError: unknown
  for (let port = PREVIEW_PORT_START; port <= PREVIEW_PORT_END; port++) {
    if (!(await isPortAvailable(port))) continue
    try {
      const preview = await startPreviewServer(previewDir, appRoot, port)
      return { ...preview, port }
    } catch (err) {
      lastError = err
    }
  }
  throw lastError instanceof Error ? lastError : new Error('No local preview port is available')
}

export async function POST(req: NextRequest) {
  // Local preview requires a writable filesystem — unavailable on Vercel serverless.
  // Return a clear skip signal so the pipeline continues without failing.
  if (process.env.VERCEL || process.env.VERCEL_ENV || process.env.AWS_LAMBDA_FUNCTION_NAME) {
    return NextResponse.json({
      ok: false,
      error: 'Local preview is not available in serverless deployments. Files have been generated and will be pushed to GitHub.',
      isServerless: true,
    }, { status: 200 })
  }

  const session = await requireSession()
  if (session.error) return session.error

  let body: LocalPreviewBody
  try {
    body = await req.json() as LocalPreviewBody
  } catch {
    return NextResponse.json({ ok: false, error: 'Invalid JSON body' }, { status: 400 })
  }

  const incomingFiles = body.files ?? {}
  const entries = Object.entries(incomingFiles).filter(([, content]) => typeof content === 'string')
  if (entries.length === 0) {
    return NextResponse.json({ ok: false, error: 'No generated files available for local preview' }, { status: 400 })
  }
  if (entries.length > MAX_FILES) {
    return NextResponse.json({ ok: false, error: `Too many files for local preview (${entries.length}/${MAX_FILES})` }, { status: 400 })
  }

  const projectName = slugify(body.projectName || 'nexus-preview')
  const runId = `${new Date().toISOString().replace(/[^0-9]/g, '').slice(0, 14)}-${Math.random().toString(36).slice(2, 7)}`
  const { repoRoot, appRoot } = resolveWorkspaceRoots()
  const previewRoot = path.join(repoRoot, '.nexus-previews')
  const previewDir = path.join(previewRoot, `${projectName}-${runId}`)

  await mkdir(previewDir, { recursive: true })

  const filesToWrite = { ...baseFiles(projectName), ...incomingFiles }
  const written: string[] = []
  const skipped: string[] = []

  for (const [filePath, rawContent] of Object.entries(filesToWrite)) {
    const safePath = safeRelativeFilePath(filePath)
    const content = typeof rawContent === 'string' ? rawContent.slice(0, MAX_FILE_CHARS) : ''
    if (!safePath || !content.trim()) {
      skipped.push(filePath)
      continue
    }
    const target = path.join(previewDir, safePath)
    if (!target.startsWith(previewDir)) {
      skipped.push(filePath)
      continue
    }
    await mkdir(path.dirname(target), { recursive: true })
    await writeFile(target, content, 'utf8')
    written.push(filePath)
  }

  let nodeModulesLinked = false
  try {
    await symlink(path.join(appRoot, 'node_modules'), path.join(previewDir, 'node_modules'), 'junction')
    nodeModulesLinked = true
  } catch {
    nodeModulesLinked = false
  }

  let preview: Awaited<ReturnType<typeof startPreviewServerWithPortRetry>>
  try {
    preview = await startPreviewServerWithPortRetry(previewDir, appRoot)
  } catch (err) {
    const message = (err as Error).message || 'Local preview server could not be started'
    return NextResponse.json({
      ok: false,
      error: message,
      data: {
        path: previewDir,
        projectName,
        fileCount: written.length,
        skipped,
        nodeModulesLinked,
      },
    }, { status: 200 })
  }

  return NextResponse.json({
    ok: preview.ready,
    ...(preview.ready ? {} : { error: `Local preview files were written, but the dev server did not respond at ${preview.url}. Check ${preview.logPath}` }),
    data: {
      path: previewDir,
      projectName,
      fileCount: written.length,
      skipped,
      nodeModulesLinked,
      url: preview.url,
      port: preview.port,
      ready: preview.ready,
      command: preview.command,
      logPath: preview.logPath,
    },
  }, { status: 200 })
}
