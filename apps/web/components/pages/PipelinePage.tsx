function formatAgentDuration(ms: number): string {
  if (ms < 1000) return `${ms}ms`
  if (ms < 60_000) return `${(ms / 1000).toFixed(ms < 10_000 ? 1 : 0)}s`
  const mins = Math.floor(ms / 60_000)
  const secs = Math.round((ms % 60_000) / 1000)
  return `${mins}m ${secs}s`
}

function formatAgentFinishedAt(iso: string): string {
  return new Date(iso).toLocaleTimeString('en', {
    hour12: false,
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  })
}

function formatRemainingDuration(totalSeconds: number): string {
  if (totalSeconds <= 0) return 'wrapping up...'
  const mins = Math.floor(totalSeconds / 60)
  const secs = totalSeconds % 60
  return mins > 0 ? `~${mins}m ${secs}s left` : `~${secs}s left`
}

function MiniBars({ value, tone = 'acid' }: { value: number; tone?: 'acid' | 'cyan' | 'rose' }) {
  const color = tone === 'cyan' ? 'bg-cyan-300' : tone === 'rose' ? 'bg-rose-400' : 'bg-[#c8f23c]'
  return (
    <div className="flex h-8 items-end gap-0.5" aria-hidden>
      {Array.from({ length: 18 }).map((_, i) => {
        const wave = Math.sin((i + 1) * 0.85) * 18 + Math.cos(i * 0.35) * 10
        const h = Math.max(14, Math.min(100, value * 0.55 + 28 + wave))
        return <span key={i} className={`w-1 rounded-t-sm ${color}/80`} style={{ height: `${h}%`, opacity: 0.35 + (i % 5) * 0.12 }} />
      })}
    </div>
  )
}

function validateProductionAppReadiness(files: Record<string, string>): string[] {
  const issues: string[] = []
  const read = (file: string) => files[file] ?? ''
  const required = [
    'package.json',
    'src/app/layout.tsx',
    'src/app/page.tsx',
    'src/app/globals.css',
    'src/lib/types.ts',
    'src/lib/data.ts',
    'src/components/ui.tsx',
    'src/components/forms.tsx',
    'src/components/modals.tsx',
    'src/hooks/useApp.ts',
    'src/app/dashboard/layout.tsx',
    'src/app/dashboard/page.tsx',
    'src/app/dashboard/[feature]/page.tsx',
    'src/app/api/health/route.ts',
    'src/app/api/data/route.ts',
    'src/app/api/search/route.ts',
  ]
  const missing = required.filter(file => !read(file).trim())
  if (missing.length > 0) issues.push(`Missing production app files: ${missing.join(', ')}`)

  const clientSurface = [
    read('src/components/forms.tsx'),
    read('src/components/modals.tsx'),
    read('src/hooks/useApp.ts'),
    read('src/app/dashboard/page.tsx'),
    read('src/app/dashboard/[feature]/page.tsx'),
  ].join('\n')
  if (!/useState|useReducer|useLocalStorage|useFilter|useModal/.test(clientSurface)) {
    issues.push('No meaningful client-side state/workflow layer detected')
  }
  if (!/onSubmit|onChange|onClick|<form|<select|<textarea/.test(clientSurface)) {
    issues.push('No user-operable forms, filters, actions, or workflow controls detected')
  }
  if (!/URL\.createObjectURL|Blob|download|router\.push|set[A-Z][A-Za-z]+\(/.test(clientSurface)) {
    issues.push('No export, navigation, mutation, or business action behavior detected')
  }

  const apiSurface = [
    read('src/app/api/health/route.ts'),
    read('src/app/api/data/route.ts'),
    read('src/app/api/search/route.ts'),
  ].join('\n')
  if (!/export\s+async\s+function\s+GET|export\s+function\s+GET/.test(apiSurface)) {
    issues.push('API routes do not expose valid GET handlers')
  }
  if (!/NextResponse\.json|Response\.json/.test(apiSurface)) {
    issues.push('API routes do not return JSON responses')
  }

  const data = read('src/lib/data.ts')
  const exportedArrays = data.match(/export\s+const\s+[A-Za-z0-9_]+\s*(?::[^=]+)?=\s*\[/g) ?? []
  // Match both string-quoted IDs ({ id: 'x' }) and numeric IDs ({ id: 1 }) — AI output varies
  const objectRecordCount = (data.match(/\{\s*id:\s*['"`\d]/g) ?? []).length
  // Require at least 2 exported arrays OR 8+ records with id fields (relaxed from 10; AI varies on format)
  if (exportedArrays.length < 2 || objectRecordCount < 8) {
    issues.push('Domain data is too thin for a real working application')
  }

  // Hard placeholder signals — these alone in a file indicate truly unfilled template content
  const hardPlaceholderPattern = /coming soon|placeholder\s+(copy|content|text)|lorem ipsum|sample only|static preview|safety baseline|John Doe/i
  // Bracket tokens like [Feature] or [MAIN_ENTITY] are common in AI-generated code when MOCK DATA
  // fails. A single occurrence in an otherwise complete file should NOT block deploy — require ≥ 3
  // occurrences in one file to count it as a real placeholder match.
  const bracketPattern = /\[(Feature|slug|Entity|MAIN_ENTITY|field|Product Name)[^\]]*\]/gi
  const matchingFiles = Object.values(files).filter(src => {
    const s = src
      .replace(/\splaceholder\s*=\s*(['"`])[\s\S]*?\1/g, '')
      .replace(/\/\/[^\n]*/g, '')
      .replace(/\/\*[\s\S]*?\*\//g, '')
    if (hardPlaceholderPattern.test(s)) return true
    // Count bracket token occurrences — require ≥ 3 to flag as unresolved template
    const bracketMatches = s.match(bracketPattern)
    return bracketMatches !== null && bracketMatches.length >= 3
  })
  // Require ≥ 3 flagged files to block deploy — a single agent's imperfect output
  // should not prevent shipping when 26 other files are production-ready
  if (matchingFiles.length >= 3) {
    issues.push('Placeholder/static/demo-only language detected in generated source')
  }

  return issues
}

